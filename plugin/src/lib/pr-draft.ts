/**
 * Change-request drafting: the prompt a model receives and the parsing of its
 * answer.
 *
 * Everything here is pure text handling, so the shape the model must return is
 * testable without a model, a repository, or a code host.
 */

import type { PullConfig } from './config.ts'
import type { LlmService, ModelRoute } from '../host/dsh.ts'

/** Longest title this plugin sends to a code host. */
export const MAX_TITLE_LENGTH = 140
/** Longest description this plugin sends to a code host. */
export const MAX_BODY_LENGTH = 24000

/** Language name used in the instruction, from the UI locale. */
const LANGUAGES = new Map<string, string>([
  ['vi', 'Vietnamese'],
  ['en', 'English'],
  ['zh', 'Chinese'],
  ['ja', 'Japanese'],
  ['es', 'Spanish'],
  ['fr', 'French'],
  ['de', 'German'],
  ['ru', 'Russian'],
  ['pt', 'Portuguese'],
])

/** One file a branch changed, for the drafting prompt. */
export interface ChangeRequestFile {
  path: string
  additions: number
  deletions: number
}

/** One commit a branch adds, for the drafting prompt. */
export interface ChangeRequestCommit {
  subject: string
  author?: string
  date?: string
}

/** The facts a change-request draft is built from. */
export interface ChangeRequestFacts {
  branch: string
  base: string
  /** How many commits the branch adds over its base. */
  ahead?: number
  commits?: ChangeRequestCommit[]
  files?: ChangeRequestFile[]
  diff?: string
  truncated?: boolean
  locale?: string
}

/** One parsed change-request draft. */
export interface ChangeRequestDraft {
  title: string
  body: string
  parsed: 'json' | 'text' | 'fallback'
}

/** What one model call needs to draft a change request. */
export interface DraftChangeRequestOptions {
  llm: LlmService | undefined
  route: ModelRoute | null
  sessionId?: string
  facts: ChangeRequestFacts
  branch: string
  base: string
  locale?: string
  config: Partial<PullConfig>
  signal?: AbortSignal
  logger?: { warn?: (...args: unknown[]) => void }
}

/** One drafted change request, with the reason when the model did not answer. */
export interface DraftedChangeRequest {
  title: string
  body: string
  source: 'commits' | 'model'
  model: string | null
  error?: string
  /** The reasoning effort the route settled on, when it advertises one. */
  chosen?: string | null
}

/** The instruction that frames one drafting request. */
export function changeRequestSystemPrompt(locale = 'en'): string {
  const language = languageName(locale)
  return [
    'You are a senior engineer writing the title and description of a pull request that is about to be opened against its base branch.',
    'You receive JSON: the branch, its base, how many commits it adds, the commit subjects, the changed files with line counts, and a unified diff. The diff is the source of truth; commit subjects may be terse or written in another language.',
    'Answer with one JSON object and nothing else: {"title": string, "body": string}.',
    `The title is one line of at most 90 characters in ${language}, without a trailing period. Name the concrete user-visible change. Never use a generic title such as "Update files", "Changes", "Fix bug", "WIP", or the branch name.`,
    `The body is Markdown written in ${language}. It has exactly three sections, in this order, with their headings translated into ${language}:`,
    '1. a short summary paragraph (two to four sentences) that says what changes and why, supported by the diff;',
    '2. a "Changes" section with three to six bullets, each naming the affected file, module, or behavior and what changed;',
    '3. a "Testing" section with bullets describing how the change was verified according to the input; when the input shows no tests or verification, say plainly that tests were not run.',
    'Keep paths, identifiers, commands, and commit hashes verbatim. Do not repeat the title as the first line of the body.',
    'Describe only what the diff and commits show. Never invent a file, a test, a reason, a reviewer, an issue number, or a benchmark result.',
    'Do not quote the raw diff, add checklists, emojis, badges, or a "Generated by" line, and do not mention that an AI wrote this.',
  ].join('\n')
}

/** The display name of one locale's language, or English for an unknown one. */
function languageName(locale: string): string {
  return LANGUAGES.get(String(locale ?? '').slice(0, 2).toLowerCase()) ?? 'English'
}

/**
 * The facts one draft needs, as the JSON the model reads.
 *
 * @param facts the branch, its commits, its files, and the diff excerpt.
 */
export function buildChangeRequestInput(facts: ChangeRequestFacts): string {
  const payload = {
    branch: facts.branch,
    base: facts.base,
    ahead: Number(facts.ahead) || (facts.commits?.length ?? 0),
    commits: (facts.commits ?? []).map((commit) => ({
      subject: commit.subject,
      ...(commit.author === undefined ? {} : { author: commit.author }),
    })),
    files: (facts.files ?? []).map((file) => ({
      path: file.path,
      additions: file.additions,
      deletions: file.deletions,
    })),
    fileCount: (facts.files ?? []).length,
    diffTruncated: facts.truncated === true,
    diff: facts.diff ?? '',
  }
  return [
    `Draft the pull request that opens ${facts.branch} against ${facts.base}. Read the diff before writing.`,
    '```json',
    JSON.stringify(payload),
    '```',
    'Answer with the JSON object only.',
  ].join('\n')
}

/**
 * Read a model answer as a change-request draft.
 *
 * Models sometimes wrap JSON in a code fence or add a sentence before it, so a
 * fence is stripped and the outermost JSON object is located before a plain
 * "first line is the title" fallback is tried.
 *
 * @param text model output.
 * @param options title used when the answer is unusable.
 */
export function parseChangeRequestDraft(text: string, options: { fallbackTitle?: string } = {}): ChangeRequestDraft {
  const raw = String(text ?? '').trim()
  const fallbackTitle = normalizeTitle(options.fallbackTitle ?? '')
  if (raw.length === 0) {
    return { title: fallbackTitle, body: '', parsed: 'fallback' }
  }

  const jsonText = extractJsonObject(raw)
  if (jsonText !== null) {
    try {
      const value: unknown = JSON.parse(jsonText)
      const record = value !== null && typeof value === 'object' ? (value as Record<string, unknown>) : {}
      const title = normalizeTitle(String(record.title ?? ''))
      const body = normalizeBody(String(record.body ?? record.description ?? ''))
      if (title.length > 0) return { title, body, parsed: 'json' }
    } catch {
      // A malformed object still leaves the readable text below.
    }
  }

  const lines = raw.split(/\r?\n/)
  const titleLine = lines.find((line) => line.trim().length > 0) ?? ''
  const title = normalizeTitle(stripMarkdown(titleLine))
  if (title.length === 0) {
    return { title: fallbackTitle, body: stripFence(raw), parsed: 'fallback' }
  }
  const rest = lines.slice(lines.indexOf(titleLine) + 1).join('\n').trim()
  return { title, body: normalizeBody(stripFence(rest)), parsed: 'text' }
}

/**
 * Locate the outermost JSON object in a model answer.
 * @param text model output.
 * @returns the object text, or null when there is none.
 */
export function extractJsonObject(text: string): string | null {
  const unwrapped = stripFence(text)
  const start = unwrapped.indexOf('{')
  if (start < 0) return null
  let depth = 0
  let inString = false
  let escaped = false
  for (let index = start; index < unwrapped.length; index += 1) {
    const character = unwrapped[index]
    if (inString) {
      if (escaped) escaped = false
      else if (character === '\\') escaped = true
      else if (character === '"') inString = false
      continue
    }
    if (character === '"') inString = true
    else if (character === '{') depth += 1
    else if (character === '}') {
      depth -= 1
      if (depth === 0) return unwrapped.slice(start, index + 1)
    }
  }
  return null
}

/** Remove one surrounding Markdown code fence, if present. */
export function stripFence(text: string): string {
  const trimmed = String(text ?? '').trim()
  const fenced = /^```[A-Za-z0-9_-]*\s*\n([\s\S]*?)\n?```$/.exec(trimmed)
  return fenced === null ? trimmed : fenced[1].trim()
}

/** Trim a title to one clean line within the code host's limit. */
export function normalizeTitle(text: string): string {
  const single = String(text ?? '')
    .replace(/\s+/g, ' ')
    .replace(/^#+\s*/, '')
    .replace(/^["'`]+|["'`]+$/g, '')
    .replace(/^\*{1,3}(.*?)\*{1,3}$/, '$1')
    .trim()
  return single.length <= MAX_TITLE_LENGTH ? single : `${single.slice(0, MAX_TITLE_LENGTH - 1).trimEnd()}…`
}

/** Trim a description to the length a code host accepts. */
export function normalizeBody(text: string): string {
  const body = String(text ?? '').replace(/\r\n/g, '\n').trim()
  if (body.length <= MAX_BODY_LENGTH) return body
  return `${body.slice(0, MAX_BODY_LENGTH - 1).trimEnd()}…`
}

/** Titles that name nothing, so a draft carrying one is retried. */
const GENERIC_TITLE = /^(update|updates|change|changes|fix|fixes|bug ?fix|wip|tmp|temp|test|tests|patch|misc|miscellaneous|edit|edits|refactor)(\s+(files?|code|stuff|things?|bugs?|changes?|repo|project|branch|panel))?$/i

/**
 * Whether a parsed draft is concrete enough to open a pull request with.
 *
 * A model can answer with a title only, with a generic title, or with a body
 * that is one sentence; those are retried rather than published.
 *
 * @param title the normalized title.
 * @param body the normalized description.
 */
export function draftIsUsable(title: string, body: string): boolean {
  const cleanTitle = normalizeTitle(title)
  const cleanBody = normalizeBody(body)
  if (cleanTitle.length < 12) return false
  if (GENERIC_TITLE.test(cleanTitle)) return false
  if (cleanBody.length < 80) return false
  if (!cleanBody.includes('\n')) return false
  if (!(/^#{1,3}\s+\S/m.test(cleanBody) || /^\s*[-*+]\s+\S/m.test(cleanBody))) return false
  return cleanBody !== cleanTitle
}

/** Strip emphasis and a leading list marker from a fallback title line. */
function stripMarkdown(text: string): string {
  return String(text ?? '')
    .replace(/^[-*+]\s+/, '')
    .replace(/^\*\*(.*)\*\*$/, '$1')
    .trim()
}

/**
 * A complete draft for a branch whose model answer was unusable, from the
 * facts alone, so the action still produces a reviewable change request.
 *
 * The description follows the reader's language: Vietnamese for a `vi` locale,
 * English otherwise.
 *
 * @param facts the branch, its commits, and its files.
 * @param locale the UI locale, such as `vi` or `en`.
 */
export function offlineDraft(
  facts: Pick<ChangeRequestFacts, 'branch' | 'base' | 'commits' | 'files'>,
  locale = 'en',
): { title: string; body: string } {
  const vietnamese = languageName(locale) === 'Vietnamese'
  const commits = facts.commits ?? []
  const files = facts.files ?? []
  const title = normalizeTitle(
    commits[0]?.subject
      ?? (vietnamese ? `Gộp ${facts.branch} vào ${facts.base}` : `Merge ${facts.branch} into ${facts.base}`),
  )
  const lines = vietnamese
    ? [
        commits.length === 0
          ? `Mở thay đổi từ \`${facts.branch}\` vào \`${facts.base}\`.`
          : `Nhánh \`${facts.branch}\` gộp ${commits.length} commit vào \`${facts.base}\`.`,
        '',
        '## Thay đổi',
        ...files.slice(0, 20).map((file) => `- \`${file.path}\` (+${file.additions} −${file.deletions})`),
      ]
    : [
        commits.length === 0
          ? `Open the change from \`${facts.branch}\` into \`${facts.base}\`.`
          : `Branch \`${facts.branch}\` adds ${commits.length} commit${commits.length === 1 ? '' : 's'} over \`${facts.base}\`.`,
        '',
        '## Changes',
        ...files.slice(0, 20).map((file) => `- \`${file.path}\` (+${file.additions} −${file.deletions})`),
      ]
  if (files.length > 20) lines.push(vietnamese ? `- … và ${files.length - 20} tệp khác` : `- … and ${files.length - 20} more files`)
  if (commits.length > 1) {
    lines.push('', vietnamese ? '## Commit' : '## Commits', ...commits.slice(0, 20).map((commit) => `- ${commit.subject}`))
  }
  lines.push('', vietnamese ? '## Kiểm thử' : '## Testing', vietnamese ? '- Chưa chạy kiểm thử cho thay đổi này.' : '- Tests were not run for this change.')
  return { title, body: normalizeBody(lines.join('\n')) }
}

/**
 * Draft one change request with a model, falling back to the commits.
 *
 * The reasoning effort is the lowest the route advertises: a title and two
 * paragraphs need no deliberation, and the user asked for the current model at
 * its cheapest setting. Any failure — no LLM service, an aborted request, an
 * unusable answer — returns the commit-derived draft with the reason recorded
 * instead of failing the whole action.
 */
export async function draftChangeRequest({
  llm,
  route,
  sessionId = '',
  facts,
  branch,
  base,
  locale,
  config,
  signal,
  logger,
}: DraftChangeRequestOptions): Promise<DraftedChangeRequest> {
  const fallback: DraftedChangeRequest = {
    ...offlineDraft({ branch, base, commits: facts.commits ?? [], files: facts.files ?? [] }, locale ?? 'en'),
    source: 'commits',
    model: null,
  }
  if (llm === undefined || typeof llm.prepareCall !== 'function') return { ...fallback, error: 'model-unavailable' }
  if (route === null || typeof route?.provider !== 'string' || typeof route?.model !== 'string') {
    return { ...fallback, error: 'model-unavailable' }
  }

  const timeoutMs = Math.max(5000, Number(config?.timeoutMs) || 90000)
  const deadline = AbortSignal.timeout(timeoutMs)
  const combined = signal === undefined ? deadline : AbortSignal.any([signal, deadline])
  try {
    const call = await llm.prepareCall(
      { provider: route.provider, model: route.model, maxTokens: Number(config?.maxOutputTokens) || 4096 },
      combined,
      (controls, model) => {
        const efforts = (model as { reasoning?: { efforts?: Array<{ id?: string }> } } | null | undefined)?.reasoning?.efforts
        const effort = efforts?.[0]?.id
        return effort === undefined ? controls : { ...controls, reasoningEffort: effort }
      },
    )
    const system = changeRequestSystemPrompt(locale)
    const baseInput = buildChangeRequestInput({
      branch,
      base,
      ahead: facts.ahead,
      commits: facts.commits ?? [],
      files: facts.files ?? [],
      diff: facts.diff ?? '',
      truncated: facts.truncated === true,
    })

    /** Ask once and read the answer as a draft. */
    const ask = async (note: string): Promise<{ title: string; body: string; parsed: string }> => {
      let streamed = ''
      const blocks: string[] = []
      for await (const chunk of call.stream({
        ...call.config,
        messages: [{ role: 'user', content: [{ type: 'text', text: note.length === 0 ? baseInput : `${baseInput}\n\n${note}` }] }],
        system,
        ...(sessionId.length === 0 ? {} : { sessionId }),
        signal: combined,
      })) {
        if (chunk?.type === 'text-delta' && typeof chunk.text === 'string') streamed += chunk.text
        else if (chunk?.type === 'block-end' && chunk.block?.type === 'text' && typeof chunk.block.text === 'string') {
          blocks.push(chunk.block.text)
        }
      }
      return parseChangeRequestDraft(blocks.length > 0 ? blocks.join('\n') : streamed, { fallbackTitle: fallback.title })
    }

    let draft = await ask('')
    // A title-only, generic, or one-line answer is rewritten once with a
    // pointed correction; publishing a vague description is worse than a retry.
    if (!draftIsUsable(draft.title, draft.body)) {
      logger?.warn?.('pr: the first change-request draft was unusable, retrying')
      draft = await ask([
        'Your previous answer was not usable as a pull request description.',
        `Return the JSON object again with a concrete title that names this change (not "Update", "Changes", or "${branch}")`,
        'and a body of at least three sentences plus the three required sections and their bullets, written in the requested language.',
      ].join(' '))
    }
    if (draft.parsed === 'fallback') return { ...fallback, error: 'unparsed-answer' }
    if (!draftIsUsable(draft.title, draft.body)) return { ...fallback, error: 'unusable-answer' }
    return {
      title: draft.title,
      body: draft.body,
      source: 'model',
      model: `${route.provider}/${route.model}`,
      chosen: call.config?.reasoningEffort ?? null,
    }
  } catch (error) {
    if (signal?.aborted === true) throw error
    logger?.warn?.('pr: the change-request draft failed: %s', messageOf(error))
    return { ...fallback, error: messageOf(error) }
  }
}

/** Message of an unknown thrown value. */
function messageOf(error: unknown): string {
  return error instanceof Error ? error.message : String(error)
}
