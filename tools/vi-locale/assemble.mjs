/**
 * Assemble translated chunk files into the bundle's generated Vietnamese
 * dictionary module, validating them against the English source snapshot.
 *
 * usage:
 *   node tools/vi-locale/assemble.mjs <en-dicts.json> <translationsDir> <target.ts>
 *
 * Every chunk file must have the shape
 *   { "namespaces": { "<ns>": { "vi": { "<key>": "<string>" } } } }
 * and is matched against the English dictionary of the same namespace: the key
 * sets and the `{placeholder}` sets must be identical. Keys a chunk omits stay
 * out of the generated module, so the UI falls back to English for them.
 */
import fs from 'node:fs'
import path from 'node:path'

const [enPath, outDir, target] = process.argv.slice(2)
if (!enPath || !outDir || !target) {
  console.error('usage: node tools/vi-locale/assemble.mjs <en-dicts.json> <outDir> <target.ts>')
  process.exit(2)
}

const en = JSON.parse(fs.readFileSync(enPath, 'utf8')).namespaces
const chunkFiles = fs.readdirSync(outDir).filter((name) => name.endsWith('.json')).sort()
const translated = new Map()
const problems = []

const placeholderRe = /\{[^{}\s]+\}/g
const placeholders = (text) => [...text.matchAll(placeholderRe)].map((match) => match[0]).sort()

for (const file of chunkFiles) {
  const chunk = JSON.parse(fs.readFileSync(path.join(outDir, file), 'utf8'))
  for (const [ns, locales] of Object.entries(chunk.namespaces ?? {})) {
    const dict = locales.vi ?? locales.en
    if (dict === undefined) {
      problems.push(`${file}: namespace ${ns} has no vi dictionary`)
      continue
    }
    const source = en[ns]
    if (source === undefined) {
      problems.push(`${file}: unknown namespace ${ns}`)
      continue
    }
    const existing = translated.get(ns) ?? {}
    for (const [key, value] of Object.entries(dict)) {
      if (!(key in source)) {
        problems.push(`${file}: ${ns} has unknown key ${key}`)
        continue
      }
      // Separator-only strings are punctuation or whitespace by design; keep
      // the English value instead of translating it.
      if (source[key].trim() === '') {
        existing[key] = source[key]
        continue
      }
      if (typeof value !== 'string' || value.trim() === '') {
        problems.push(`${file}: ${ns}.${key} is empty`)
        continue
      }
      const wanted = placeholders(source[key]).join(',')
      const got = placeholders(value).join(',')
      if (wanted !== got) {
        problems.push(`${file}: ${ns}.${key} placeholders differ ({${wanted}} vs {${got}})`)
        continue
      }
      if (/[\u200B\uFEFF]/.test(value)) {
        problems.push(`${file}: ${ns}.${key} contains a zero-width character`)
        continue
      }
      existing[key] = value
    }
    translated.set(ns, existing)
  }
}

const namespaces = [...translated.keys()].sort((a, b) => a.localeCompare(b))
let total = 0
const missing = []
const lines = []
for (const ns of namespaces) {
  const dict = translated.get(ns)
  const source = en[ns]
  const missingKeys = Object.keys(source).filter((key) => !(key in dict))
  if (missingKeys.length > 0) missing.push(`${ns}: ${missingKeys.length} key(s) fall back to English`)
  total += Object.keys(dict).length
  const entries = Object.keys(dict)
    .sort((a, b) => a.localeCompare(b))
    .map((key) => `    ${JSON.stringify(key)}: ${JSON.stringify(dict[key])},`)
    .join('\n')
  lines.push(`  ${JSON.stringify(ns)}: {\n${entries}\n  },`)
}

const header = `/**
 * Vietnamese dictionaries for the Harness web GUI, keyed by Harness locale
 * namespace.
 *
 * GENERATED by tools/vi-locale/assemble.mjs from translated chunk files. Do not
 * hand-edit an entry unless you also keep the chunk files in sync; re-run the
 * assembler instead.
 *
 * Namespaces and keys come from the installed Harness: a string this pack does
 * not translate falls back to English through the language's fallback chain.
 */
export const VI_DICTIONARIES: Record<string, Record<string, string>> = {
`
fs.writeFileSync(target, `${header}${lines.join('\n')}\n}\n`)

console.log(`namespaces=${namespaces.length} keys=${total} -> ${target}`)
if (problems.length > 0) {
  console.log(`--- problems (${problems.length}) ---`)
  for (const problem of problems.slice(0, 80)) console.log(problem)
}
if (missing.length > 0) {
  console.log(`--- keys that fall back to English (${missing.length} namespace(s)) ---`)
  for (const line of missing) console.log(line)
}
if (problems.length > 0) process.exitCode = 1
